class SuricataRulesEngine:
    """Search, query, and inspection engine for Suricata network signatures."""

    @classmethod
    def get_rule(cls, sid: int) -> Optional[SuricataRule]:
        return SURICATA_CATALOG.get(sid)

    @classmethod
    def get_rules_by_protocol(cls, protocol: str) -> List[SuricataRule]:
        p_lower = protocol.lower()
        return [r for r in SURICATA_CATALOG.values() if r.protocol.lower() == p_lower]

    @classmethod
    def get_rules_by_classtype(cls, classtype: str) -> List[SuricataRule]:
        return [r for r in SURICATA_CATALOG.values() if r.classtype == classtype]

    @classmethod
    def search(cls, query: str) -> List[SuricataRule]:
        q = query.lower()
        return [
            r for r in SURICATA_CATALOG.values()
            if q in r.msg.lower() or q in r.cve_id.lower() or q in r.content_match.lower()
        ]

    @classmethod
    def inspect_payload(cls, payload_str: str) -> List[SuricataRule]:
        matched = []
        for rule in SURICATA_CATALOG.values():
            if rule.content_match in payload_str:
                matched.append(rule)
        return matched

    @classmethod
    def get_catalog_summary(cls) -> Dict[str, Any]:
        protocols = {}
        classtypes = {}
        for r in SURICATA_CATALOG.values():
            protocols[r.protocol] = protocols.get(r.protocol, 0) + 1
            classtypes[r.classtype] = classtypes.get(r.classtype, 0) + 1

        return {
            "total_rules": len(SURICATA_CATALOG),
            "protocols": protocols,
            "classtypes": classtypes
        }
