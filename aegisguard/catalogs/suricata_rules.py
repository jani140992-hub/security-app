from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional, Any, Set


class RuleAction(str, Enum):
    ALERT = "alert"
    DROP = "drop"
    PASS = "pass"


@dataclass
class SuricataRule:
    sid: int
    msg: str
    protocol: str
    source_net: str
    source_port: str
    dest_net: str
    dest_port: str
    action: RuleAction
    classtype: str
    content_match: str
    cve_id: str
    mitre_technique: str
    rev: int = 1
    raw_rule: str = ""

    def __post_init__(self):
        if not self.raw_rule:
            self.raw_rule = f'{self.action.value} {self.protocol} {self.source_net} {self.source_port} -> {self.dest_net} {self.dest_port} (msg:"{self.msg}"; content:"{self.content_match}"; classtype:{self.classtype}; sid:{self.sid}; rev:{self.rev};)'


