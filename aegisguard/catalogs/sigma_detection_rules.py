class SigmaRuleCompiler:
    """
    Rule compilation, pattern matching, and AST query translation engine.
    Matches raw event dictionaries against Sigma detection rules.
    """

    @classmethod
    def match_selection(cls, event: Dict[str, Any], selection: Dict[str, Any]) -> bool:
        if not selection:
            return False

        for field_expr, expected_values in selection.items():
            # Handle modifiers: |endswith, |contains, |startswith
            field_name = field_expr
            modifier = "exact"
            if "|" in field_expr:
                field_name, modifier = field_expr.split("|", 1)

            actual_value = event.get(field_name)
            if actual_value is None:
                # Try case-insensitive lookup
                for k, v in event.items():
                    if k.lower() == field_name.lower():
                        actual_value = v
                        break

            if actual_value is None:
                return False

            actual_str = str(actual_value)
            matched = False
            for exp in expected_values:
                exp_str = str(exp)
                if modifier == "endswith" and actual_str.lower().endswith(exp_str.lower()):
                    matched = True
                    break
                elif modifier == "contains" and exp_str.lower() in actual_str.lower():
                    matched = True
                    break
                elif modifier == "startswith" and actual_str.lower().startswith(exp_str.lower()):
                    matched = True
                    break
                elif modifier == "exact" and actual_str.lower() == exp_str.lower():
                    matched = True
                    break

            if not matched:
                return False

        return True

    @classmethod
    def evaluate_rule(cls, event: Dict[str, Any], rule: SigmaRule) -> bool:
        sel_match = cls.match_selection(event, rule.detection_selection)
        if not sel_match:
            return False

        if rule.detection_filter:
            flt_match = cls.match_selection(event, rule.detection_filter)
            if flt_match:
                return False

        return True

    @classmethod
    def scan_event(cls, event: Dict[str, Any]) -> List[SigmaRule]:
        matched_rules = []
        for rule in SIGMA_CATALOG.values():
            if cls.evaluate_rule(event, rule):
                matched_rules.append(rule)
        return matched_rules

    @classmethod
    def get_by_category(cls, category: str) -> List[SigmaRule]:
        return [r for r in SIGMA_CATALOG.values() if r.category == category]

    @classmethod
    def get_by_mitre_tag(cls, mitre_tag: str) -> List[SigmaRule]:
        tag_lower = mitre_tag.lower()
        return [r for r in SIGMA_CATALOG.values() if any(tag_lower in t.lower() for t in r.tags)]

    @classmethod
    def compile_to_spl(cls, rule: SigmaRule) -> str:
        tokens = []
        for k, vals in rule.detection_selection.items():
            clean_k = k.split("|")[0]
            val_str = " OR ".join(f'{clean_k}="*{v}*"' for v in vals)
            tokens.append(f"({val_str})")
        return f"index=security sourcetype={rule.product} " + " AND ".join(tokens)

    @classmethod
    def get_catalog_summary(cls) -> Dict[str, Any]:
        total = len(SIGMA_CATALOG)
        critical = sum(1 for r in SIGMA_CATALOG.values() if r.level == RuleLevel.CRITICAL)
        high = sum(1 for r in SIGMA_CATALOG.values() if r.level == RuleLevel.HIGH)
        medium = sum(1 for r in SIGMA_CATALOG.values() if r.level == RuleLevel.MEDIUM)

        categories = {}
        for r in SIGMA_CATALOG.values():
            categories[r.category] = categories.get(r.category, 0) + 1

        return {
            "total_rules": total,
            "critical_rules": critical,
            "high_rules": high,
            "medium_rules": medium,
            "categories": categories
        }
